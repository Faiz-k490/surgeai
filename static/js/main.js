const textarea = document.getElementById("inputText");
const charCount = document.getElementById("charCount");
const analyzeBtn = document.getElementById("analyzeBtn");
const btnText = document.getElementById("btnText");
const btnSpinner = document.getElementById("btnSpinner");
const errorMsg = document.getElementById("errorMsg");
const resultsDiv = document.getElementById("results");

// Character counter
textarea.addEventListener("input", () => {
  charCount.textContent = `${textarea.value.length} characters`;
});

// Sample buttons
document.querySelectorAll(".sample-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    const key = btn.dataset.sample;
    textarea.value = SAMPLES[key] || "";
    charCount.textContent = `${textarea.value.length} characters`;
    textarea.focus();
  });
});

// Analyze
analyzeBtn.addEventListener("click", runAnalysis);
textarea.addEventListener("keydown", (e) => {
  if ((e.ctrlKey || e.metaKey) && e.key === "Enter") runAnalysis();
});

async function runAnalysis() {
  const text = textarea.value.trim();
  errorMsg.classList.add("d-none");

  if (!text) {
    showError("Please enter some text to analyze.");
    return;
  }

  setLoading(true);

  try {
    const res = await fetch("/analyze", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text }),
    });

    const data = await res.json();

    if (!res.ok) {
      showError(data.error || "Something went wrong. Please try again.");
      return;
    }

    renderResults(data);
  } catch (err) {
    showError("Network error. Please check your connection and try again.");
  } finally {
    setLoading(false);
  }
}

function setLoading(on) {
  analyzeBtn.disabled = on;
  btnText.textContent = on ? "Analyzing…" : "⚡ Analyze Surge";
  btnSpinner.classList.toggle("d-none", !on);
}

function showError(msg) {
  errorMsg.textContent = msg;
  errorMsg.classList.remove("d-none");
}

function renderResults(data) {
  const { surge, keywords, summary, word_count, ai_powered } = data;

  // Score circle (CSS conic-gradient trick)
  const scoreCircle = document.getElementById("scoreCircle");
  scoreCircle.style.setProperty("--pct", `${surge.score}%`);
  document.getElementById("scoreValue").textContent = surge.score;

  // Surge level badge
  const lvlBadge = document.getElementById("surgeLevel");
  lvlBadge.textContent = surge.level;
  lvlBadge.className = `surge-level-badge ${surge.color}`;

  // Score bar
  const bar = document.getElementById("scoreBar");
  bar.style.width = "0%";
  requestAnimationFrame(() => {
    bar.style.width = `${surge.score}%`;
  });

  // Summary
  document.getElementById("summaryText").textContent = summary;
  document.getElementById("aiLabel").textContent = ai_powered
    ? "✨ Summary generated by GPT-4o-mini"
    : "📊 Summary generated by built-in analyzer";

  // Stats
  document.getElementById("wordCount").textContent = word_count.toLocaleString();

  const sentimentIcons = { Positive: "😊", Negative: "😟", Neutral: "😐" };
  document.getElementById("sentimentIcon").textContent = sentimentIcons[surge.sentiment] || "😐";
  document.getElementById("sentimentValue").textContent = surge.sentiment;

  document.getElementById("urgencyCount").textContent = surge.urgency_hits.length;

  // Keywords
  const cloud = document.getElementById("keywordCloud");
  cloud.innerHTML = "";
  const maxCount = keywords[0]?.count || 1;
  keywords.forEach(({ word, count, pct }) => {
    const intensity = count / maxCount;
    const opacity = Math.round(40 + intensity * 60);
    const pill = document.createElement("span");
    pill.className = "keyword-pill";
    pill.style.cssText = `
      background: rgba(108,71,255,${opacity / 100});
      border-color: rgba(108,71,255,${opacity / 100 + 0.2});
      color: rgba(255,255,255,${0.6 + intensity * 0.4});
      font-size: ${0.78 + intensity * 0.22}rem;
    `;
    pill.textContent = `${word} ×${count}`;
    cloud.appendChild(pill);
  });

  // Signal breakdown
  const breakdown = document.getElementById("signalBreakdown");
  const signals = [
    {
      label: "Positive Signals",
      score: surge.pos_score,
      max: 35,
      color: "#63d98a",
      hits: surge.positive_hits,
      tagColor: "rgba(99,217,138,0.2)",
      tagBorder: "rgba(99,217,138,0.4)",
    },
    {
      label: "Negative Signals",
      score: surge.neg_score,
      max: 30,
      color: "#ff6b6b",
      hits: surge.negative_hits,
      tagColor: "rgba(255,107,107,0.2)",
      tagBorder: "rgba(255,107,107,0.4)",
    },
    {
      label: "Urgency Signals",
      score: surge.urgency_score,
      max: 35,
      color: "#ffd56b",
      hits: surge.urgency_hits,
      tagColor: "rgba(255,213,107,0.2)",
      tagBorder: "rgba(255,213,107,0.4)",
    },
  ];

  breakdown.innerHTML = signals
    .map(
      ({ label, score, max, color, hits, tagColor, tagBorder }) => `
    <div class="signal-row">
      <div class="signal-label">
        <span>${label}</span>
        <span>${score}/${max}</span>
      </div>
      <div class="signal-bar-track">
        <div class="signal-bar-fill" style="width:${(score / max) * 100}%; background:${color};"></div>
      </div>
      ${
        hits.length
          ? `<div class="signal-tags">${hits
              .map(
                (h) =>
                  `<span class="signal-tag" style="background:${tagColor};border-color:${tagBorder};color:${color}">${h}</span>`
              )
              .join("")}</div>`
          : `<p class="text-muted small mt-1 mb-0">No signals detected</p>`
      }
    </div>
  `
    )
    .join("");

  // Show results
  resultsDiv.classList.remove("d-none");
  resultsDiv.scrollIntoView({ behavior: "smooth", block: "start" });
}
