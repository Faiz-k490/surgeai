-- SurgeonAI Snowflake bootstrap + probe defaults
-- Run in Snowsight as ACCOUNTADMIN

-- 1) Core objects for backend
CREATE DATABASE IF NOT EXISTS SURGEAI_DB;
CREATE SCHEMA IF NOT EXISTS SURGEAI_DB.PUBLIC;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 2) Active worksheet context
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE SURGEAI_DB;
USE SCHEMA PUBLIC;

-- 3) Ensure connector sessions inherit DB/schema defaults
ALTER USER ROTINDI SET
  DEFAULT_WAREHOUSE = COMPUTE_WH,
  DEFAULT_ROLE = ACCOUNTADMIN,
  DEFAULT_NAMESPACE = SURGEAI_DB.PUBLIC;

-- 4) Verify context
SELECT
  CURRENT_ACCOUNT(),
  CURRENT_USER(),
  CURRENT_ROLE(),
  CURRENT_WAREHOUSE(),
  CURRENT_DATABASE(),
  CURRENT_SCHEMA();
